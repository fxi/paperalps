export type IconName = keyof typeof ICONS;

/** An inline icon element (inherits colour, hidden from screen readers). */
export function icon(name: IconName, cls = ''): SVGSVGElement {
  const t = document.createElement('template');
  t.innerHTML = ICONS[name].trim();
  const s = t.content.firstElementChild as SVGSVGElement;
  s.setAttribute('class', `ico ${cls}`.trim());
  s.setAttribute('aria-hidden', 'true');
  s.setAttribute('focusable', 'false');
  return s;
}

/** Fill every `[data-icon]` element under `root` with its icon (static markup in index.html). */
export function hydrateIcons(root: ParentNode = document): void {
  for (const el of root.querySelectorAll<HTMLElement>('[data-icon]')) {
    const name = el.dataset.icon as IconName;
    if (!(name in ICONS)) continue;
    el.replaceWith(icon(name, el.dataset.iconClass ?? ''));
  }
}
